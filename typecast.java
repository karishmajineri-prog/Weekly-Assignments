package typecasting;

public class typecast {

	public static void main(String[] args) {
		// Storing the value in a double
		
		double num = 10.75; ///This is a double datatype
		int num1= (int) num; //typecasting double into int
		System.out.println("Double : "+ num); //Printing double num
		System.out.println("Explicitly Typecasted Num : " + num1); //Printing typecasted num

	}

}
